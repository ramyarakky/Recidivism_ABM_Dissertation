def load_and_validate(path):
    df = pd.read_csv(path)

    required = PREDICTORS + TARGETS + [GROUP_COL]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            "Required columns missing from dataset: "
            f"{missing}. This revised analysis requires '{GROUP_COL}' so that "
            "entire ABM simulations can be held out during evaluation."
        )

    if df[GROUP_COL].isna().any():
        raise ValueError(f"{GROUP_COL} contains missing values.")

    n_groups = int(df[GROUP_COL].nunique())
    if n_groups < 3:
        raise ValueError(
            f"At least 3 independent simulation seeds are required; found {n_groups}."
        )

    # Keep the master cohort here. Each horizon is filtered independently below
    # so missingness at one follow-up horizon does not unnecessarily remove records.
    return df


def make_onehot_encoder():
    """
    Return a dense OneHotEncoder so all requested classifiers, including
    Gaussian Naive Bayes and Gradient Boosting, receive compatible matrices.
    Compatible with both newer and older scikit-learn releases.
    """
    try:
        return OneHotEncoder(handle_unknown="ignore", sparse_output=False)
    except TypeError:
        return OneHotEncoder(handle_unknown="ignore", sparse=False)


def build_preprocessor(X):
    categorical_cols = [
        c for c in X.columns
        if X[c].dtype == "object"
        or str(X[c].dtype).startswith("category")
        or X[c].dtype == bool
    ]
    numeric_cols = [c for c in X.columns if c not in categorical_cols]

    numeric_pipe = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
        ]
    )
    categorical_pipe = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", make_onehot_encoder()),
        ]
    )

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", numeric_pipe, numeric_cols),
            ("cat", categorical_pipe, categorical_cols),
        ]
    )
    return preprocessor, numeric_cols, categorical_cols


