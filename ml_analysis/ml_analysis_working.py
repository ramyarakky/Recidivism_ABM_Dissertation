def binary_metrics(y_true, prob, threshold=0.5):
    pred = (prob >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, pred, labels=[0, 1]).ravel()

    specificity = tn / (tn + fp) if (tn + fp) else np.nan
    sensitivity = tp / (tp + fn) if (tp + fn) else np.nan
    fpr = fp / (fp + tn) if (fp + tn) else np.nan

    return {
        "Accuracy": accuracy_score(y_true, pred),
        "Precision": precision_score(y_true, pred, zero_division=0),
        "Recall_Sensitivity": sensitivity,
        "Specificity": specificity,
        "F1": f1_score(y_true, pred, zero_division=0),
        "ROC_AUC": roc_auc_score(y_true, prob),
        "PR_AUC": average_precision_score(y_true, prob),
        "Brier": brier_score_loss(y_true, prob),
        "FPR": fpr,
        "TN": int(tn),
        "FP": int(fp),
        "FN": int(fn),
        "TP": int(tp),
    }


def _cv_fit_score_task(
    model_name,
    pipeline,
    fold_number,
    train_idx,
    val_idx,
    X_train,
    y_train,
    groups_train,
):
    """Fit one model on one inner-CV fold and return all requested validation metrics."""
    model = clone(pipeline)

    X_fit = X_train.iloc[train_idx]
    y_fit = y_train.iloc[train_idx]
    X_val = X_train.iloc[val_idx]
    y_val = y_train.iloc[val_idx]

    model.fit(X_fit, y_fit)
    prob = model.predict_proba(X_val)[:, 1]
    metrics = binary_metrics(y_val.to_numpy(dtype=int), prob)

    validation_seeds = pd.Series(groups_train.iloc[val_idx]).unique().tolist()
    validation_seed = (
        validation_seeds[0]
        if len(validation_seeds) == 1
        else ",".join(map(str, validation_seeds))
    )

    return {
        "Model": model_name,
        "Inner_Fold": int(fold_number),
        "Validation_Seed": validation_seed,
        "Accuracy": float(metrics["Accuracy"]),
        "Precision": float(metrics["Precision"]),
        "Sensitivity": float(metrics["Recall_Sensitivity"]),
        "Specificity": float(metrics["Specificity"]),
        "F1": float(metrics["F1"]),
        "ROC_AUC": float(metrics["ROC_AUC"]),
        "PR_AUC": float(metrics["PR_AUC"]),
        "Brier": float(metrics["Brier"]),
    }


def _final_fit_predict_task(
    model_name,
    pipeline,
    X_train,
    y_train,
    X_test,
    y_test,
    heldout_seed,
    unique_train_groups,
):
    """Fit one final model on all training seeds and predict the unseen outer test seed."""
    model = clone(pipeline)
    model.fit(X_train, y_train)
    prob = model.predict_proba(X_test)[:, 1]

    metrics = binary_metrics(y_test.to_numpy(dtype=int), prob)
    metrics["Model"] = model_name
    metrics["Heldout_Seed"] = heldout_seed
    metrics["Train_N"] = int(len(y_train))
    metrics["Test_N"] = int(len(y_test))
    metrics["Train_Seed_Count"] = int(unique_train_groups)

    return model_name, model, prob, metrics


def evaluate_models_grouped(
    models,
    X_train,
    y_train,
    groups_train,
    X_test,
    y_test,
    heldout_seed,
    workers,
):
    """
    HPC-optimized grouped evaluation.

    Parallel strategy
    -----------------
    Inner CV:
        10 models x 4 group folds = 40 independent model-fold fits.
        These are executed concurrently up to --workers.

    Final outer fit:
        The 10 models are fitted concurrently on all four training simulations,
        then evaluated on the completely unseen held-out simulation.

    Individual estimators are configured with n_jobs=1 so nested model-level
    threading does not oversubscribe the 64-core node.
    """
    unique_train_groups = pd.Series(groups_train).nunique()
    inner_splits = min(N_SPLITS, int(unique_train_groups))
    if inner_splits < 2:
        raise ValueError("At least two training simulation seeds are required for inner CV.")

    cv = GroupKFold(n_splits=inner_splits)
    cv_splits = list(cv.split(X_train, y_train, groups_train))

    n_models = len(models)
    n_cv_tasks = n_models * len(cv_splits)
    cv_workers = max(1, min(int(workers), n_cv_tasks))

    print(
        f"    HPC inner CV: {n_models} models x {len(cv_splits)} folds "
        f"= {n_cv_tasks} fits | workers={cv_workers}"
    )

    cv_jobs = []
    for model_name, pipeline in models.items():
        for fold_number, (train_idx, val_idx) in enumerate(cv_splits, start=1):
            cv_jobs.append(
                delayed(_cv_fit_score_task)(
                    model_name=model_name,
                    pipeline=pipeline,
                    fold_number=fold_number,
                    train_idx=train_idx,
                    val_idx=val_idx,
                    X_train=X_train,
                    y_train=y_train,
                    groups_train=groups_train,
                )
            )

    # loky gives true process-level parallelism. inner_max_num_threads=1
    # prevents BLAS/OpenMP libraries inside each worker from spawning more
    # threads and exhausting the node.
    with parallel_backend("loky", inner_max_num_threads=1):
        cv_results = Parallel(
            n_jobs=cv_workers,
            verbose=5,
            pre_dispatch=cv_workers,
            batch_size=1,
        )(cv_jobs)

    cv_fold_df = pd.DataFrame(cv_results)
    cv_fold_df.insert(0, "Heldout_Seed", heldout_seed)

    # Summarize the four inner validation folds for each model.
    cv_summary_rows = []
    cv_metrics = [
        "Accuracy", "Precision", "Sensitivity", "Specificity",
        "F1", "ROC_AUC", "PR_AUC", "Brier",
    ]
    for model_name in MODEL_ORDER:
        g = cv_fold_df[cv_fold_df["Model"] == model_name]
        if g.empty:
            continue

        row = {
            "Heldout_Seed": heldout_seed,
            "Model": model_name,
            "Inner_CV_Folds": inner_splits,
        }
        for metric in cv_metrics:
            values = g[metric].astype(float).to_numpy()
            row[f"CV_{metric}_Mean"] = float(np.mean(values))
            row[f"CV_{metric}_SD"] = (
                float(np.std(values, ddof=1)) if len(values) > 1 else np.nan
            )
        cv_summary_rows.append(row)

    cv_summary_df = pd.DataFrame(cv_summary_rows)

    # Final fit for this outer split: ten independent models can also run concurrently.
    final_workers = max(1, min(int(workers), n_models))
    print(
        f"    HPC final outer fit: {n_models} models | workers={final_workers} "
        f"| held-out seed={heldout_seed}"
    )

    final_jobs = [
        delayed(_final_fit_predict_task)(
            model_name=name,
            pipeline=pipeline,
            X_train=X_train,
            y_train=y_train,
            X_test=X_test,
            y_test=y_test,
            heldout_seed=heldout_seed,
            unique_train_groups=unique_train_groups,
        )
        for name, pipeline in models.items()
    ]

    with parallel_backend("loky", inner_max_num_threads=1):
        final_results = Parallel(
            n_jobs=final_workers,
            verbose=5,
            pre_dispatch=final_workers,
            batch_size=1,
        )(final_jobs)

    fitted = {}
    predictions = {}
    test_rows = []

    for model_name, fitted_model, prob, metrics in final_results:
        fitted[model_name] = fitted_model
        predictions[model_name] = prob
        test_rows.append(metrics)

    # Preserve requested model order in output.
    test_df = (
        pd.DataFrame(test_rows)
        .set_index("Model")
        .reindex(MODEL_ORDER)
        .reset_index()
    )

    return fitted, predictions, test_df, cv_summary_df, cv_fold_df


def summarize_inner_cv_results(cv_fold_df):
    """
    Aggregate raw inner validation-fold results across all outer held-out-seed runs.

    Each model typically contributes 20 validation results per horizon:
    5 outer splits × 4 inner folds.
    """
    metrics = [
        "Accuracy", "Precision", "Sensitivity", "Specificity",
        "F1", "ROC_AUC", "PR_AUC", "Brier",
    ]
    rows = []
    for model in MODEL_ORDER:
        g = cv_fold_df[cv_fold_df["Model"] == model]
        if g.empty:
            continue
        row = {
            "Model": model,
            "N_Inner_Validation_Folds": int(len(g)),
        }
        for metric in metrics:
            vals = g[metric].astype(float)
            row[metric] = float(vals.mean())
            row[f"{metric}_SD"] = float(vals.std(ddof=1)) if len(vals) > 1 else np.nan
            row[f"{metric}_Min"] = float(vals.min())
            row[f"{metric}_Max"] = float(vals.max())
        rows.append(row)
    return pd.DataFrame(rows)


