def _finite_plot_values(*arrays):
    """Flatten numeric inputs and return only finite values."""
    vals = []
    for arr in arrays:
        if arr is None:
            continue
        try:
            a = np.asarray(arr, dtype=float).ravel()
        except Exception:
            continue
        vals.extend(a[np.isfinite(a)].tolist())
    return np.asarray(vals, dtype=float)


def set_relevant_ylim(
    ax,
    *arrays,
    include=None,
    hard_min=None,
    hard_max=None,
    padding=0.10,
    min_span=0.02,
    symmetric_about=None,
):
    """Apply a compact, data-relevant y-axis range."""
    vals = _finite_plot_values(*arrays)
    if include is not None:
        vals = np.concatenate([vals, np.atleast_1d(include).astype(float)])

    if vals.size == 0:
        return

    lo = float(np.nanmin(vals))
    hi = float(np.nanmax(vals))

    if symmetric_about is not None:
        center = float(symmetric_about)
        radius = max(abs(lo - center), abs(hi - center), min_span / 2)
        radius *= (1.0 + padding)
        lo, hi = center - radius, center + radius
    else:
        span = max(hi - lo, min_span)
        pad = span * padding
        lo -= pad
        hi += pad

    if hard_min is not None:
        lo = max(float(hard_min), lo)
    if hard_max is not None:
        hi = min(float(hard_max), hi)

    if hi <= lo:
        hi = lo + min_span

    ax.set_ylim(lo, hi)


