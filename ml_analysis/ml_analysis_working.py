    for model in model_order:
        g = (
            d[d["Model"] == model]
            .set_index("Horizon")
            .reindex(horizon_order)
        )
        y = g[metric].astype(float).to_numpy()

        ax.plot(
            x,
            y,
            marker="o",
            linewidth=2.2,
            markersize=7,
            label=model,
        )

        # Label all held-out point estimates so the figure can stand alone in a dissertation.
        for xi, yi in zip(x, y):
            if np.isfinite(yi):
                ax.annotate(
                    format(yi, value_fmt),
                    (xi, yi),
                    xytext=(0, 8),
                    textcoords="offset points",
                    ha="center",
                    va="bottom",
                    fontsize=8.5,
                )

    ax.set_xticks(x)
    ax.set_xticklabels(horizon_order)
    ax.set_xlabel("Rearrest prediction horizon")
    ax.set_ylabel(ylabel)
    ax.set_title(title, fontweight="bold")
    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False, ncol=2, loc="best")

    ylim = _metric_ylim(
        d[metric],
        lower_floor=lower_floor,
        upper_ceiling=upper_ceiling,
    )
    if ylim is not None:
        ax.set_ylim(*ylim)

    fig.text(
        0.5,
        0.01,
        note,
        ha="center",
        fontsize=9,
    )
    compact_figure(fig, bottom=0.075)
    fig.savefig(charts_dir / filename, dpi=350, bbox_inches="tight")
    plt.close(fig)


