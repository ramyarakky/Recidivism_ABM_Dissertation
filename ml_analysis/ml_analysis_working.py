def _best_model_name_from_fairness(fair_df, fallback="Selected model"):
    """Return the actual best-model name stored in a horizon fairness table."""
    if fair_df is not None and "Best_Model" in fair_df.columns:
        vals = fair_df["Best_Model"].dropna().astype(str)
        vals = vals[vals.str.strip().ne("")]
        if not vals.empty:
            return vals.iloc[0]
    return fallback


def _best_model_title_across_horizons(df, horizon_order=None):
    """
    Build a compact title fragment from actual selected models.

    If the same model is selected at every horizon, return just that model name.
    Otherwise return a horizon-to-model mapping.
    """
    if horizon_order is None:
        horizon_order = ["3-Year", "6-Year", "9-Year"]

    if df is None or "Horizon" not in df.columns:
        return "Selected models"

    model_col = "Best_Model" if "Best_Model" in df.columns else (
        "Model" if "Model" in df.columns else None
    )
    if model_col is None:
        return "Selected models"

    mapping = {}
    for horizon in horizon_order:
        g = df[df["Horizon"].astype(str).eq(horizon)]
        vals = g[model_col].dropna().astype(str)
        vals = vals[vals.str.strip().ne("")]
        if not vals.empty:
            mapping[horizon] = vals.iloc[0]

    if not mapping:
        return "Selected models"

    unique_models = list(dict.fromkeys(mapping.values()))
    if len(unique_models) == 1:
        return unique_models[0]

    return "; ".join(
        f"{h}: {mapping.get(h, 'Unknown')}" for h in horizon_order
    )


