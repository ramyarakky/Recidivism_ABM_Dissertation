def compute_grouped_permutation_importance(
    fold_artifacts,
    best_model_name,
    repeats,
    tables_dir,
    charts_dir,
    horizon_label,
    workers,
):
    """Aggregate permutation importance across complete held-out simulation seeds."""
    per_seed_rows = []

    for heldout_seed, artifact in fold_artifacts.items():
        model = artifact["fitted"][best_model_name]
        X_test = artifact["X_test"]
        y_test = artifact["y_test"]

        result = permutation_importance(
            model,
            X_test,
            y_test,
            scoring="roc_auc",
            n_repeats=repeats,
            random_state=RANDOM_STATE,
            n_jobs=max(1, int(workers)),
        )

        for feature, imp_mean, imp_sd in zip(
            X_test.columns, result.importances_mean, result.importances_std
        ):
            per_seed_rows.append(
                {
                    "Heldout_Seed": heldout_seed,
                    "Feature": feature,
                    "Importance_Mean": float(imp_mean),
                    "Importance_SD_Within_Seed": float(imp_sd),
                }
            )

    per_seed = pd.DataFrame(per_seed_rows)
    per_seed.to_csv(
        tables_dir / f"{horizon_label.lower().replace(chr(45), chr(95))}_best_model_permutation_importance_by_seed.csv",
        index=False,
    )

    agg = (
        per_seed.groupby("Feature", as_index=False)
        .agg(
            Importance_Mean=("Importance_Mean", "mean"),
            Importance_SD_Across_Seeds=("Importance_Mean", "std"),
            N_Seeds=("Heldout_Seed", "nunique"),
        )
        .sort_values("Importance_Mean", ascending=False)
    )
    agg.to_csv(
        tables_dir / f"{horizon_label.lower().replace(chr(45), chr(95))}_best_model_permutation_importance.csv",
        index=False,
    )

    top = agg.head(15).sort_values("Importance_Mean", ascending=True)
    fig, ax = plt.subplots(figsize=(8.8, 6.1))
    ax.barh(
        top["Feature"],
        top["Importance_Mean"],
        xerr=top["Importance_SD_Across_Seeds"].fillna(0),
        capsize=3,
    )
    ax.axvline(0, linewidth=1)
    ax.set_xlabel("Mean decrease in ROC-AUC after permutation")
    ax.set_title(f"Top Predictors Across Held-Out Seeds: {horizon_label} Rearrest")
    ax.grid(axis="x", alpha=0.25)
    set_relevant_xlim(
        ax,
        top["Importance_Mean"].to_numpy(dtype=float),
        include=0.0,
        padding=0.08,
        min_span=0.01,
    )
    fig.text(
        0.5, 0.01,
        "Bars show mean predictive contribution across held-out simulation seeds; error bars show between-seed SD.",
        ha="center", fontsize=9,
    )
    compact_figure(fig, bottom=0.07)
    fig.savefig(
        charts_dir / f"ML7_{horizon_label.lower().replace(chr(45), chr(95))}_permutation_importance.png",
        dpi=350, bbox_inches="tight",
    )
    plt.close(fig)
    return agg


