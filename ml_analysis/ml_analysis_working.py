def subgroup_point_metrics(y, prob):
    y = np.asarray(y, dtype=int)
    prob = np.asarray(prob, dtype=float)
    pred = (prob >= 0.5).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()

    out = {
        "N": len(y),
        "Prevalence": np.mean(y),
        "TPR": tp / (tp + fn) if (tp + fn) else np.nan,
        "FPR": fp / (fp + tn) if (fp + tn) else np.nan,
        "Precision": tp / (tp + fp) if (tp + fp) else np.nan,
        "Brier": brier_score_loss(y, prob),
    }
    out["ROC_AUC"] = roc_auc_score(y, prob) if len(np.unique(y)) == 2 else np.nan
    return out


def bootstrap_group_metrics(y, prob, n_boot, rng):
    y = np.asarray(y, dtype=int)
    prob = np.asarray(prob, dtype=float)
    n = len(y)

    metric_names = ["ROC_AUC", "TPR", "FPR", "Brier"]
    vals = {m: [] for m in metric_names}

    for _ in range(n_boot):
        idx = rng.integers(0, n, size=n)
        yb = y[idx]
        pb = prob[idx]

        if len(np.unique(yb)) < 2:
            continue

        m = subgroup_point_metrics(yb, pb)
        for metric in metric_names:
            if np.isfinite(m[metric]):
                vals[metric].append(m[metric])

    cis = {}
    for metric in metric_names:
        arr = np.asarray(vals[metric], dtype=float)
        if len(arr) == 0:
            cis[metric] = (np.nan, np.nan)
        else:
            cis[metric] = (
                float(np.percentile(arr, 2.5)),
                float(np.percentile(arr, 97.5)),
            )
    return cis


def _comparative_fairness_point_table(
    X_test,
    y_test,
    prob,
    group_col,
    reference_group,
    threshold=0.5,
):
    """
    Calculate subgroup point estimates plus comparative fairness metrics.

    Positive class = predicted rearrest, an adverse outcome.

    Comparative metrics:
      DIR  = subgroup predicted-positive rate / reference predicted-positive rate
      DPD  = subgroup predicted-positive rate - reference predicted-positive rate
      TPR difference = subgroup TPR - reference TPR
      FPR difference = subgroup FPR - reference FPR

    Parity values:
      DIR = 1.0
      DPD = 0.0
      TPR difference = 0.0
      FPR difference = 0.0
    """
    work = pd.DataFrame(
        {
            "group": X_test[group_col].astype(str).values,
            "y": np.asarray(y_test, dtype=int),
            "prob": np.asarray(prob, dtype=float),
        }
    )
    work["pred"] = (work["prob"].to_numpy() >= threshold).astype(int)

    rows = []
    for group, g in work.groupby("group", sort=True):
        y = g["y"].to_numpy(dtype=int)
        p = g["prob"].to_numpy(dtype=float)
        pred = g["pred"].to_numpy(dtype=int)

        tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()

        tpr = tp / (tp + fn) if (tp + fn) else np.nan
        fpr = fp / (fp + tn) if (fp + tn) else np.nan
        precision = tp / (tp + fp) if (tp + fp) else np.nan
        roc_auc = roc_auc_score(y, p) if len(np.unique(y)) == 2 else np.nan
        brier = brier_score_loss(y, p)

        rows.append(
            {
                "Dimension": group_col,
                "Group": str(group),
                "Reference_Group": str(reference_group),
                "N": int(len(g)),
                "Prevalence": float(np.mean(y)),
                "Predicted_Positive_Rate": float(np.mean(pred)),
                "TPR": float(tpr) if np.isfinite(tpr) else np.nan,
                "FPR": float(fpr) if np.isfinite(fpr) else np.nan,
                "Precision": float(precision) if np.isfinite(precision) else np.nan,
                "ROC_AUC": float(roc_auc) if np.isfinite(roc_auc) else np.nan,
                "Brier": float(brier),
                "TN": int(tn),
                "FP": int(fp),
                "FN": int(fn),
                "TP": int(tp),
            }
        )

    out = pd.DataFrame(rows)
    ref = out[out["Group"].eq(str(reference_group))]
    if ref.empty:
        raise ValueError(
            f"Reference group '{reference_group}' not found for {group_col}. "
            f"Available groups: {out['Group'].tolist()}"
        )

    ref_row = ref.iloc[0]
    ref_selection = float(ref_row["Predicted_Positive_Rate"])
    ref_tpr = float(ref_row["TPR"])
    ref_fpr = float(ref_row["FPR"])

    out["Reference_Predicted_Positive_Rate"] = ref_selection
    out["Disparate_Impact_Ratio"] = (
        out["Predicted_Positive_Rate"] / ref_selection
        if ref_selection > 0 else np.nan
    )
    out["Demographic_Parity_Difference"] = (
        out["Predicted_Positive_Rate"] - ref_selection
    )
    out["TPR_Difference"] = out["TPR"] - ref_tpr
    out["FPR_Difference"] = out["FPR"] - ref_fpr

    return out


def fairness_table(X_test, y_test, prob, group_col, n_boot):
    """
    Build dissertation fairness table with bootstrap 95% confidence intervals.

    The reference groups are White for Race and Male for Gender.
    Bootstrap resampling is performed on pooled leave-one-simulation-out
    predictions, so every analyzed probability remains out-of-simulation.
    """
    reference_group = FAIRNESS_REFERENCE_GROUPS[group_col]

    base = _comparative_fairness_point_table(
        X_test=X_test,
        y_test=y_test,
        prob=prob,
        group_col=group_col,
        reference_group=reference_group,
    )

    metric_names = [
        "Predicted_Positive_Rate",
        "Disparate_Impact_Ratio",
        "Demographic_Parity_Difference",
        "TPR",
        "TPR_Difference",
        "FPR",
        "FPR_Difference",
        "ROC_AUC",
        "Brier",
    ]

    rng = np.random.default_rng(RANDOM_STATE)
    X_reset = X_test.reset_index(drop=True)
    y_arr = np.asarray(y_test, dtype=int)
    p_arr = np.asarray(prob, dtype=float)
    n = len(y_arr)

    boot_values = {
        (group, metric): []
        for group in base["Group"].astype(str)
        for metric in metric_names
    }

    for _ in range(int(n_boot)):
        idx = rng.integers(0, n, size=n)

        Xb = X_reset.iloc[idx].reset_index(drop=True)
        yb = y_arr[idx]
        pb = p_arr[idx]

        try:
            boot = _comparative_fairness_point_table(
                X_test=Xb,
                y_test=yb,
                prob=pb,
                group_col=group_col,
                reference_group=reference_group,
            )
        except ValueError:
            # Reference group can very rarely disappear in a bootstrap sample.
            continue

        for _, row in boot.iterrows():
            group = str(row["Group"])
            for metric in metric_names:
                val = row[metric]
                if pd.notna(val) and np.isfinite(val):
                    boot_values[(group, metric)].append(float(val))

    for metric in metric_names:
        lows, highs = [], []
        for group in base["Group"].astype(str):
            arr = np.asarray(boot_values[(group, metric)], dtype=float)
            if len(arr):
                lo, hi = np.percentile(arr, [2.5, 97.5])
            else:
                lo, hi = np.nan, np.nan
            lows.append(lo)
            highs.append(hi)

        base[f"{metric}_CI95_Low"] = lows
        base[f"{metric}_CI95_High"] = highs

    return base


def _error_arrays(d, metric):
    """Return non-negative asymmetric error arrays for matplotlib."""
    center = d[metric].astype(float).to_numpy()
    lo = d[f"{metric}_CI95_Low"].astype(float).to_numpy()
    hi = d[f"{metric}_CI95_High"].astype(float).to_numpy()
    return np.vstack([
        np.maximum(0.0, center - lo),
        np.maximum(0.0, hi - center),
    ])


