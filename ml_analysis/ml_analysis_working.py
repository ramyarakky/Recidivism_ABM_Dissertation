def _ordered_cross_horizon(all_test):
    """Return a consistently ordered model × horizon table for dissertation figures."""
    model_order = MODEL_ORDER
    horizon_order = ["3-Year", "6-Year", "9-Year"]

    d = all_test.copy()
    d["Model"] = pd.Categorical(d["Model"], categories=model_order, ordered=True)
    d["Horizon"] = pd.Categorical(d["Horizon"], categories=horizon_order, ordered=True)
    return d.sort_values(["Model", "Horizon"]).reset_index(drop=True)


def _metric_ylim(values, lower_floor=None, upper_ceiling=None, pad_fraction=0.18):
    """Create a readable non-misleading y-range with padding around observed values."""
    vals = np.asarray(pd.Series(values).dropna(), dtype=float)
    if vals.size == 0:
        return None

    lo = float(np.min(vals))
    hi = float(np.max(vals))
    span = max(hi - lo, 0.01)
    pad = span * pad_fraction

    ymin = lo - pad
    ymax = hi + pad

    if lower_floor is not None:
        ymin = max(lower_floor, ymin)
    if upper_ceiling is not None:
        ymax = min(upper_ceiling, ymax)

    if ymin >= ymax:
        ymin = lo - 0.01
        ymax = hi + 0.01

    return ymin, ymax


def plot_cross_horizon_metric_lines(
    all_test,
    charts_dir,
    metric,
    ylabel,
    title,
    filename,
    note,
    value_fmt=".3f",
    lower_floor=None,
    upper_ceiling=None,
):
    """
    Dissertation-ready cross-horizon line figure.

    Each line represents one model and connects its held-out result across
    3-, 6-, and 9-year prediction horizons. Values are taken directly from
    ALL_HORIZONS_test_model_performance.csv / all_test and are never hardcoded.
    """
    d = _ordered_cross_horizon(all_test)
    horizon_order = ["3-Year", "6-Year", "9-Year"]
    model_order = MODEL_ORDER
    x = np.arange(len(horizon_order), dtype=float)

